PUBLIC_MODE_SUFFIX = """
【当前模式】你是博客的公共助手。友善但保持距离，不透露博主隐私，不深入展开个人故事。"""

# ============================================================================

def build_system_prompt(
    mode: str = "public",
    rag_context: str = "",
    affinity_context: str = "",
    memory_context: str = "",
    personality_context: str = "",
) -> str:
    """构建完整系统提示词。"""
    parts = [SYSTEM_PROMPT_BASE]

    if mode == "public":
        parts.append(PUBLIC_MODE_SUFFIX)

    if rag_context:
        parts.append(f"\n【参考资料：博客相关文章】\n{rag_context}")

    if mode == "owner":
        if personality_context:
            parts.append(f"\n{personality_context}")
        if memory_context:
            parts.append(f"\n{memory_context}")
        if affinity_context:
            parts.append(f"\n{affinity_context}")

    return "\n".join(parts)
